DROP SCHEMA IF EXISTS clinica CASCADE;
CREATE SCHEMA clinica;
SET search_path TO clinica;

CREATE TABLE especialidad (
  idespecialidad INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(50) NOT NULL,
  plus_salarial NUMERIC(8,2) NOT NULL DEFAULT 0,
  requiere_guardia BOOLEAN NOT NULL DEFAULT FALSE,
  fecha_creacion DATE NOT NULL
);

CREATE TABLE tipo_aseguradora (
  idtipo_aseguradora INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(50) NOT NULL,
  cobertura_maxima NUMERIC(10,2) NOT NULL DEFAULT 0,
  internacional BOOLEAN NOT NULL DEFAULT FALSE,
  fecha_creacion DATE NOT NULL
);

CREATE TABLE aseguradora (
  idaseguradora INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(60) NOT NULL,
  cuota_mensual NUMERIC(8,2) NOT NULL,
  activa BOOLEAN NOT NULL DEFAULT TRUE,
  fecha_alta DATE NOT NULL,
  imagen VARCHAR(100),
  idtipo_aseguradora INTEGER NOT NULL,
  CONSTRAINT fk_aseguradora_tipo FOREIGN KEY (idtipo_aseguradora) REFERENCES tipo_aseguradora (idtipo_aseguradora) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE medico (
  idmedico INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(50) NOT NULL,
  apellidos VARCHAR(80) NOT NULL,
  num_colegiado VARCHAR(15) NOT NULL,
  salario NUMERIC(8,2) NOT NULL,
  disponible BOOLEAN NOT NULL DEFAULT TRUE,
  fecha_contratacion DATE NOT NULL,
  imagen VARCHAR(100),
  idespecialidad INTEGER NOT NULL,
  CONSTRAINT uk_num_colegiado UNIQUE (num_colegiado),
  CONSTRAINT fk_medico_especialidad FOREIGN KEY (idespecialidad) REFERENCES especialidad (idespecialidad) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE paciente (
  idpaciente INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nombre VARCHAR(50) NOT NULL,
  apellidos VARCHAR(80) NOT NULL,
  dni VARCHAR(9) NOT NULL,
  peso NUMERIC(5,2) NOT NULL,
  alergias BOOLEAN NOT NULL DEFAULT FALSE,
  fecha_nacimiento DATE NOT NULL,
  imagen VARCHAR(100),
  idaseguradora INTEGER NOT NULL,
  CONSTRAINT uk_dni UNIQUE (dni),
  CONSTRAINT fk_paciente_aseguradora FOREIGN KEY (idaseguradora) REFERENCES aseguradora (idaseguradora) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE cita (
  idcita INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  motivo VARCHAR(120) NOT NULL,
  precio NUMERIC(7,2) NOT NULL,
  pagada BOOLEAN NOT NULL DEFAULT FALSE,
  fecha_hora TIMESTAMP NOT NULL,
  imagen VARCHAR(100),
  idpaciente INTEGER NOT NULL,
  idmedico INTEGER NOT NULL,
  CONSTRAINT fk_cita_paciente FOREIGN KEY (idpaciente) REFERENCES paciente (idpaciente) ON UPDATE CASCADE ON DELETE CASCADE,
  CONSTRAINT fk_cita_medico FOREIGN KEY (idmedico) REFERENCES medico (idmedico) ON UPDATE CASCADE ON DELETE CASCADE
);

